"""``python -m ontology.generate`` — regenerate ontology artifacts from LinkML sources.

Compiles ``ontology/src/musubi.yaml`` (the single source of meaning) into committed outputs:

  ontology/generated/musubi.schema.json  — JSON Schema (structured-output + validation)
  ontology/generated/musubi_types.py     — Pydantic v2 types (imported where practical)
  ontology/generated/musubi.shacl.ttl    — SHACL shapes (schema-level validation)
  ontology/generated/context.jsonld       — JSON-LD @context (the semantic envelope)
  ontology/generated/vocabulary.md        — NL vocabulary (dual representation, CLAUDE.md §9.3)

Run via ``make gen`` after editing any LinkML source (CLAUDE.md §0-4). Outputs are committed for
reproducibility; CI regenerates and diffs. Generation is deterministic (no timestamps embedded).
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from linkml.generators.jsonschemagen import JsonSchemaGenerator
from linkml.generators.pydanticgen import PydanticGenerator
from linkml.generators.shaclgen import ShaclGenerator
from linkml_runtime.utils.schemaview import SchemaView

_HERE = Path(__file__).resolve().parent
_SRC = _HERE / "src" / "musubi.yaml"
_GEN = _HERE / "generated"

_HEADER = "# GENERATED by `make gen` from ontology/src/musubi.yaml — do not edit by hand.\n"


def _write(path: Path, content: str) -> Path:
    path.write_text(content, encoding="utf-8")
    return path


def _gen_json_schema() -> Path:
    text = JsonSchemaGenerator(str(_SRC), include_range_class_descendants=True).serialize()
    return _write(_GEN / "musubi.schema.json", text if text.endswith("\n") else text + "\n")


def _gen_pydantic() -> Path:
    text = PydanticGenerator(str(_SRC)).serialize()
    return _write(_GEN / "musubi_types.py", text if text.endswith("\n") else text + "\n")


def _gen_shacl() -> Path:
    """Generate SHACL, then canonicalize to sorted canonical N-Triples for determinism.

    LinkML's SHACL uses blank-node property shapes; rdflib serializes those in nondeterministic
    order. We canonicalize blank-node labels (RGDA1) and sort the triples so the committed
    artifact is byte-stable across runs (CI diffs it). Canonical N-Triples is a valid Turtle
    subset, so pyshacl loads ``musubi.shacl.ttl`` unchanged.
    """
    from rdflib import Graph
    from rdflib.compare import to_canonical_graph

    ttl = ShaclGenerator(str(_SRC)).serialize()
    graph = Graph().parse(data=ttl, format="turtle")
    canonical = to_canonical_graph(graph)
    nt = canonical.serialize(format="nt")
    body = "\n".join(sorted(line for line in nt.splitlines() if line.strip()))
    return _write(_GEN / "musubi.shacl.ttl", _HEADER + body + "\n")


def _gen_jsonld_context(view: SchemaView) -> Path:
    """A minimal, deterministic JSON-LD @context: prefixes + one term per class/slot/enum.

    Hand-rolled (rather than LinkML's context generator) so the envelope @context is stable and
    free of generation metadata. The prefix map plus class/slot terms is all the bus needs.
    """
    import json

    schema = view.schema
    prefixes = {p.prefix_prefix: str(p.prefix_reference) for p in schema.prefixes.values()}
    default = schema.default_prefix or "msb"
    base = prefixes.get(default, "https://musubi.dev/ontology/musubi/")

    class_names = set(view.all_classes())
    _xsd = {
        "float": "xsd:float",
        "double": "xsd:double",
        "integer": "xsd:integer",
        "boolean": "xsd:boolean",
        "datetime": "xsd:dateTime",
        "date": "xsd:date",
    }

    def _coercion(slot_range: str | None) -> str | None:
        """JSON-LD @type coercion so data RDF matches the generated SHACL datatypes."""
        if slot_range is None:
            return None
        if slot_range in class_names or slot_range in ("uri", "uriorcurie"):
            return "@id"  # references become IRIs, not literals
        return _xsd.get(slot_range)

    terms: dict[str, Any] = {}
    for name in sorted(view.all_classes()):
        terms[name] = f"{base}{name}"
    for name in sorted(view.all_enums()):
        terms[name] = f"{base}{name}"
    for name in sorted(view.all_slots()):
        slot = view.get_slot(name)
        coerce = _coercion(slot.range if slot else None)
        if coerce is None:
            terms[name] = f"{base}{name}"
        else:
            terms[name] = {"@id": f"{base}{name}", "@type": coerce}

    context = {"@context": {**prefixes, "@vocab": base, **terms}}
    text = json.dumps(context, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    return _write(_GEN / "context.jsonld", text)


def _gen_vocabulary(view: SchemaView) -> Path:
    """NL vocabulary — the natural-language half of the dual representation (CLAUDE.md §9.3).

    Emits, for every enum / class / slot, its definition text. Deterministic (sorted).
    """
    lines: list[str] = [
        "# Musubi Ontology — Natural-Language Vocabulary",
        "",
        "> GENERATED by `make gen` from `ontology/src/musubi.yaml`. The natural-language half of "
        "the dual representation (SHACL constraints + NL definitions). Do not edit by hand.",
        "",
        f"Schema: **{view.schema.name}** v{view.schema.version}",
        "",
        "## Enumerations",
        "",
    ]
    for ename in sorted(view.all_enums()):
        e = view.get_enum(ename)
        lines.append(f"### {ename}")
        lines.append("")
        lines.append((e.description or "").strip() or "_(no description)_")
        lines.append("")
        for pv_name in sorted(e.permissible_values or {}):
            pv = e.permissible_values[pv_name]
            desc = (pv.description or "").strip()
            lines.append(f"- **{pv_name}** — {desc}")
        lines.append("")

    lines += ["## Classes", ""]
    for cname in sorted(view.all_classes()):
        c = view.get_class(cname)
        kind = "abstract " if c.abstract else ""
        parent = f" (is_a: {c.is_a})" if c.is_a else ""
        lines.append(f"### {kind}{cname}{parent}")
        lines.append("")
        lines.append((c.description or "").strip() or "_(no description)_")
        lines.append("")
        slot_names = view.class_slots(cname)
        if slot_names:
            lines.append("| slot | range | card | definition |")
            lines.append("|---|---|---|---|")
            for sname in slot_names:
                s = view.induced_slot(sname, cname)
                rng = s.range or "string"
                card = (
                    ("1..*" if s.multivalued else "1")
                    if s.required
                    else ("0..*" if s.multivalued else "0..1")
                )
                sdesc = (s.description or "").strip().replace("\n", " ")
                lines.append(f"| {sname} | {rng} | {card} | {sdesc} |")
        lines.append("")

    return _write(_GEN / "vocabulary.md", "\n".join(lines) + "\n")


def generate_all() -> list[Path]:
    if not _SRC.exists():
        raise FileNotFoundError(f"LinkML source not found: {_SRC}")
    _GEN.mkdir(parents=True, exist_ok=True)
    view = SchemaView(str(_SRC))
    written = [
        _gen_json_schema(),
        _gen_pydantic(),
        _gen_shacl(),
        _gen_jsonld_context(view),
        _gen_vocabulary(view),
    ]
    # keep the .gitkeep so the dir is tracked even before first gen
    (_GEN / ".gitkeep").touch()
    return written


def main(argv: list[str] | None = None) -> int:
    written = generate_all()
    for path in written:
        print(f"  wrote {path.relative_to(_HERE.parent)}")
    print(f"ontology: regenerated {len(written)} artifact(s) from {_SRC.name}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
