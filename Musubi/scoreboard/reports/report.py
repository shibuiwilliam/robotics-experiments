"""Experiment report generator (``make report E=<E>``).

Runs an experiment's scenarios, ingests the records into an in-memory scoreboard, and renders a
Markdown report with the ablation ladder (A0→A4) per scenario. Output goes to
``scoreboard/reports/<experiment>_report.md``.
"""

from __future__ import annotations

from pathlib import Path

from bench.runner.run import RunRecord, run_experiment
from scoreboard.metrics import MetricsStore

_REPORT_DIR = Path(__file__).resolve().parent


def _render(experiment: str, records: list[RunRecord]) -> str:
    store = MetricsStore(":memory:")
    store.ingest([r.to_dict() for r in records])
    summaries = store.arm_summaries()
    store.close()

    lines = [
        f"# Experiment {experiment} — Report",
        "",
        f"Runs: {len(records)} · scenarios: {len({r.scenario for r in records})}",
        "",
        "## Ablation ladder (per scenario × arm)",
        "",
        "| scenario | arm | n | oracle-pass | success | unappr-irrev | mean-trace | API calls |",
        "|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for s in summaries:
        lines.append(
            f"| {s.scenario} | {s.arm} | {s.n} | {s.oracle_pass_rate:.2f} | "
            f"{s.success_rate:.2f} | {s.unapproved_irreversible} | "
            f"{s.mean_trace_completeness:.2f} | {s.total_api_calls} |"
        )
    lines += [
        "",
        "## Invariants",
        "",
        f"- **Unapproved irreversible actions (must be 0):** "
        f"{sum(r.unapproved_irreversible for r in records)}",
        f"- **Total API calls (replay must be 0):** {sum(r.api_calls for r in records)}",
        f"- **Oracle-pass rate:** "
        f"{sum(r.oracle_passed for r in records) / max(1, len(records)):.2f}",
        "",
        "_Generated by `make report`. Scores use god-view oracles, never system beliefs._",
    ]
    return "\n".join(lines) + "\n"


def build_report(experiment: str, records: list[RunRecord] | None = None) -> Path:
    if records is None:
        records = run_experiment(experiment)
    text = _render(experiment, records)
    out = _REPORT_DIR / f"{experiment}_report.md"
    out.write_text(text, encoding="utf-8")
    return out
